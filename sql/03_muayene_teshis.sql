-- Örnek veriler sql/veri/03_muayene_teshis_veri.sql dosyasında.

CREATE TABLE muayene (
    muayene_id      INTEGER GENERATED BY DEFAULT AS IDENTITY,
    randevu_id      INTEGER      NOT NULL,
    muayene_tarihi  DATE         NOT NULL DEFAULT CURRENT_DATE,
    sikayet         VARCHAR(300) NOT NULL,
    notlar          VARCHAR(500),
    CONSTRAINT pk_muayene PRIMARY KEY (muayene_id),
    -- bir randevudan en fazla bir muayene çıkar
    CONSTRAINT uq_muayene_randevu UNIQUE (randevu_id),
    CONSTRAINT fk_muayene_randevu FOREIGN KEY (randevu_id)
        REFERENCES randevu (randevu_id) ON DELETE RESTRICT
);

-- Muayene kaydedilince randevunun durumu 'tamamlandi' olur.
CREATE FUNCTION muayene_randevu_tamamla() RETURNS trigger AS $$
BEGIN
    UPDATE randevu SET durum = 'tamamlandi' WHERE randevu_id = NEW.randevu_id;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_muayene_randevu_tamamla
    AFTER INSERT ON muayene
    FOR EACH ROW EXECUTE FUNCTION muayene_randevu_tamamla();

-- Teşhis kataloğu (ICD-10 kodu ve adı)
CREATE TABLE teshis (
    teshis_kodu  VARCHAR(10)  NOT NULL,
    teshis_adi   VARCHAR(150) NOT NULL,
    CONSTRAINT pk_teshis PRIMARY KEY (teshis_kodu)
);

-- Muayene ile teşhis arasındaki N-N ilişki
CREATE TABLE muayene_teshis (
    muayene_id   INTEGER      NOT NULL,
    teshis_kodu  VARCHAR(10)  NOT NULL,
    aciklama     VARCHAR(300),
    -- aynı teşhis aynı muayeneye iki kez eklenemez
    CONSTRAINT pk_muayene_teshis PRIMARY KEY (muayene_id, teshis_kodu),
    CONSTRAINT fk_muayene_teshis_muayene FOREIGN KEY (muayene_id)
        REFERENCES muayene (muayene_id) ON DELETE CASCADE,
    CONSTRAINT fk_muayene_teshis_teshis FOREIGN KEY (teshis_kodu)
        REFERENCES teshis (teshis_kodu) ON DELETE RESTRICT
);
