-- Bölüm ve doktor tabloları
-- Hazırlayan: Sude (ilk sürüm: Eray)
-- Çalıştırma sırası: 1. dosya (hasta_randevu ve muayene_teshis bu tablolara bağlanır)
-- Örnek veriler sql/veri/01_bolum_doktor_veri.sql dosyasında.

CREATE TABLE bolum (
    bolum_id   INTEGER GENERATED BY DEFAULT AS IDENTITY,
    bolum_adi  VARCHAR(50) NOT NULL,
    CONSTRAINT pk_bolum PRIMARY KEY (bolum_id),
    CONSTRAINT uq_bolum_adi UNIQUE (bolum_adi)
);

CREATE TABLE doktor (
    doktor_id  INTEGER GENERATED BY DEFAULT AS IDENTITY,
    bolum_id   INTEGER NOT NULL,
    ad         VARCHAR(50) NOT NULL,
    soyad      VARCHAR(50) NOT NULL,
    unvan      VARCHAR(30),
    telefon    VARCHAR(20),
    CONSTRAINT pk_doktor PRIMARY KEY (doktor_id),
    -- içinde doktor olan bölüm silinemez
    CONSTRAINT fk_doktor_bolum FOREIGN KEY (bolum_id)
        REFERENCES bolum (bolum_id) ON DELETE RESTRICT
);
