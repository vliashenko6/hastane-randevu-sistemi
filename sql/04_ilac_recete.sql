-- İlaç, reçete ve recete_ilac tabloları
-- Hazırlayan: Veronika
-- Çalıştırma sırası: 7. dosya (önce 03_muayene_teshis.sql çalışmalı, reçete muayeneye bağlı)
-- Örnek veriler sql/veri/04_ilac_recete_veri.sql dosyasında.

-- Hastanede yazılabilecek ilaçların listesi.
-- Aynı isimle iki ilaç kaydedilemez.
CREATE TABLE ilac (
    ilac_id      INTEGER GENERATED BY DEFAULT AS IDENTITY,
    ilac_adi     VARCHAR(100) NOT NULL,
    etken_madde  VARCHAR(150) NOT NULL,
    ilac_formu   VARCHAR(30),
    CONSTRAINT pk_ilac PRIMARY KEY (ilac_id),
    CONSTRAINT uq_ilac_adi UNIQUE (ilac_adi)
);

-- Muayene sonunda yazılan reçete.
-- Bir muayenede en fazla bir reçete yazılır, bu yüzden muayene_id tekrar edemez.
-- Hasta ve doktor bilgisi muayene -> randevu üzerinden bulunur, burada tekrar tutulmaz.
CREATE TABLE recete (
    recete_id      INTEGER GENERATED BY DEFAULT AS IDENTITY,
    muayene_id     INTEGER      NOT NULL,
    recete_tarihi  DATE         NOT NULL DEFAULT CURRENT_DATE,
    aciklama       VARCHAR(300),
    CONSTRAINT pk_recete PRIMARY KEY (recete_id),
    CONSTRAINT uq_recete_muayene UNIQUE (muayene_id),
    CONSTRAINT fk_recete_muayene FOREIGN KEY (muayene_id)
        REFERENCES muayene (muayene_id) ON DELETE RESTRICT
);

-- Reçete ile ilaç arasındaki N-N ilişki.
-- Her satır "şu reçetede şu ilaç var" demek. Doz, kullanım şekli ve kutu adedi
-- o reçetedeki o ilaca ait olduğu için burada tutulur.
CREATE TABLE recete_ilac (
    recete_id       INTEGER      NOT NULL,
    ilac_id         INTEGER      NOT NULL,
    doz             VARCHAR(20)  NOT NULL,
    kullanim_sekli  VARCHAR(150),
    kutu_adedi      SMALLINT     NOT NULL DEFAULT 1,
    -- aynı ilaç aynı reçeteye iki kez eklenemez
    CONSTRAINT pk_recete_ilac PRIMARY KEY (recete_id, ilac_id),
    CONSTRAINT ck_recete_ilac_kutu CHECK (kutu_adedi >= 1),
    -- reçete silinirse içindeki ilaç satırları da silinir
    CONSTRAINT fk_recete_ilac_recete FOREIGN KEY (recete_id)
        REFERENCES recete (recete_id) ON DELETE CASCADE,
    -- bir reçetede kullanılmış ilaç listeden silinemez
    CONSTRAINT fk_recete_ilac_ilac FOREIGN KEY (ilac_id)
        REFERENCES ilac (ilac_id) ON DELETE RESTRICT
);
