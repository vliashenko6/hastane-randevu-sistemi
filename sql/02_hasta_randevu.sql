-- Hasta ve randevu tabloları
-- Hazırlayan: Eray
-- Çalıştırma sırası: 2. dosya (01_bolum_doktor.sql çalıştırılmış olmalı)

CREATE TABLE hasta (
    hasta_id      INTEGER GENERATED BY DEFAULT AS IDENTITY,
    tc_no         CHAR(11)     NOT NULL,
    ad            VARCHAR(50)  NOT NULL,
    soyad         VARCHAR(50)  NOT NULL,
    dogum_tarihi  DATE         NOT NULL,
    cinsiyet      CHAR(1)      NOT NULL,
    telefon       VARCHAR(20)  NOT NULL,
    adres         VARCHAR(200),
    CONSTRAINT pk_hasta PRIMARY KEY (hasta_id),
    -- aynı TC ile ikinci hasta kaydedilemez
    CONSTRAINT uq_hasta_tc_no UNIQUE (tc_no),
    CONSTRAINT ck_hasta_tc_no CHECK (tc_no ~ '^[0-9]{11}$'),
    CONSTRAINT ck_hasta_dogum_tarihi CHECK (dogum_tarihi <= CURRENT_DATE),
    CONSTRAINT ck_hasta_cinsiyet CHECK (cinsiyet IN ('E', 'K'))
);

CREATE TABLE randevu (
    randevu_id      INTEGER GENERATED BY DEFAULT AS IDENTITY,
    hasta_id        INTEGER     NOT NULL,
    doktor_id       INTEGER     NOT NULL,
    randevu_tarihi  DATE        NOT NULL,
    randevu_saati   TIME        NOT NULL,
    durum           VARCHAR(10) NOT NULL DEFAULT 'aktif',
    CONSTRAINT pk_randevu PRIMARY KEY (randevu_id),
    -- randevusu olan hasta silinemez
    CONSTRAINT fk_randevu_hasta FOREIGN KEY (hasta_id)
        REFERENCES hasta (hasta_id) ON DELETE RESTRICT,
    CONSTRAINT fk_randevu_doktor FOREIGN KEY (doktor_id)
        REFERENCES doktor (doktor_id) ON DELETE RESTRICT,
    CONSTRAINT ck_randevu_durum CHECK (durum IN ('aktif', 'iptal', 'tamamlandi'))
);

-- Çift randevu engeli: aynı doktora aynı gün ve saatte tek aktif randevu olabilir.
-- İptal edilen randevular sayılmaz, o saat tekrar verilebilir.
CREATE UNIQUE INDEX uq_randevu_cift_engeli
    ON randevu (doktor_id, randevu_tarihi, randevu_saati)
    WHERE durum = 'aktif';

-- Geçmiş bir tarihe randevu verilemez.
-- CHECK yerine trigger kullandık, çünkü CHECK her güncellemede tekrar çalışır
-- ve eski bir randevunun durumunu 'tamamlandi' yapmayı engellerdi.
CREATE FUNCTION randevu_gecmis_kontrol() RETURNS trigger AS $$
BEGIN
    IF (NEW.randevu_tarihi + NEW.randevu_saati) < LOCALTIMESTAMP THEN
        RAISE EXCEPTION 'Gecmis bir tarihe randevu verilemez';
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_randevu_gecmis_kontrol
    BEFORE INSERT OR UPDATE OF randevu_tarihi, randevu_saati ON randevu
    FOR EACH ROW EXECUTE FUNCTION randevu_gecmis_kontrol();

